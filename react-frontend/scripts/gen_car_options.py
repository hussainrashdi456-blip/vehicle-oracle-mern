"""Regenerates src/data/carOptions.js from the cleaned training data so the form
only ever offers values the XGBoost label-encoders know.

Run from react-frontend/:
    python scripts/gen_car_options.py ../ai-backend/outputs/clean_data.csv
"""
import json
import sys
import pandas as pd

csv = sys.argv[1] if len(sys.argv) > 1 else "../ai-backend/outputs/clean_data.csv"
df = pd.read_csv(csv)

mode = lambda s: s.mode().iloc[0]
rows = []
for (brand, model), d in df.groupby(["Brand", "Model"]):
    if len(d) < 8:  # skip very rare models
        continue
    rows.append(dict(
        brand=brand, model=model, label=f"{brand} {model}", count=int(len(d)),
        bodyType=mode(d["Body Type"]), fuel=mode(d["Fuel"]), transmission=mode(d["Transmission"]),
        engine=int(round(d["Engine_Cleaned"].median() / 50) * 50),
    ))
rows.sort(key=lambda r: -r["count"])

provinces = [p for p, c in df.Province.value_counts().items() if c >= 5]
body_types = [b for b, c in df["Body Type"].value_counts().items() if c >= 5]
fuels = list(df.Fuel.value_counts().index)
transmissions = list(df.Transmission.value_counts().index)

out = ("// AUTO-GENERATED by scripts/gen_car_options.py from clean_data.csv. Do not edit by hand.\n"
       f"export const VEHICLES = {json.dumps(rows, separators=(",", ":"))};\n"
       f"export const PROVINCES = {json.dumps(provinces)};\n"
       f"export const BODY_TYPES = {json.dumps(body_types)};\n"
       f"export const FUELS = {json.dumps(fuels)};\n"
       f"export const TRANSMISSIONS = {json.dumps(transmissions)};\n")
open("src/data/carOptions.js", "w", encoding="utf-8").write(out)
print(len(rows), "vehicles,", len(provinces), "locations,", len(body_types), "body types")
